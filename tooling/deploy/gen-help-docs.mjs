#!/usr/bin/env node
// Bundles the admin guide (apps/admin/src/help/{tr,en}/NN-slug.md) into the Worker so the MCP help tools can serve it.
// `node tooling/deploy/gen-help-docs.mjs` writes workers/api/src/mcp/helpDocs.generated.ts; `--check` only verifies it is up to date (CI / tests).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = resolve(root, "workers/api/src/mcp/helpDocs.generated.ts");

export function render() {
  const docs = { tr: [], en: [] };
  for (const lang of Object.keys(docs)) {
    const dir = resolve(root, "apps/admin/src/help", lang);
    for (const f of readdirSync(dir).filter((n) => n.endsWith(".md")).sort()) {
      const m = /^(\d+)-([a-z0-9-]+)\.md$/.exec(f);
      if (m) docs[lang].push({ slug: m[2], order: Number(m[1]), md: readFileSync(resolve(dir, f), "utf8") });
    }
  }
  return `// GENERATED by tooling/deploy/gen-help-docs.mjs from apps/admin/src/help/*/*.md. Do not edit by hand; run \`node tooling/deploy/gen-help-docs.mjs\` (the build does).\nexport interface HelpDoc { slug: string; order: number; md: string }\nexport const HELP_DOCS: Record<"tr" | "en", HelpDoc[]> = ${JSON.stringify(docs)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render();
  if (process.argv.includes("--check")) {
    if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== next) { console.error("helpDocs.generated.ts is stale: run `node tooling/deploy/gen-help-docs.mjs`"); process.exit(1); }
    console.log("helpDocs.generated.ts is up to date");
  } else { writeFileSync(OUT, next); console.log(`wrote ${OUT} (${(next.length / 1024).toFixed(0)} KB)`); }
}
