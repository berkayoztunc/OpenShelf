#!/usr/bin/env node
/**
 * Assembles the single-Worker static site:
 *   apps/storefront/dist  ->  dist-site/          (served at /)
 *   apps/admin/dist       ->  dist-site/admin/    (served at /admin/, built with Vite base "/admin/")
 * and merges both `_headers` files into dist-site/_headers so admin-only headers (strict CSP, frame-ancestors 'none')
 * apply to /admin/* only and the storefront headers to everything else.
 * The API is now same-origin, so the old `https://api.example.com` placeholder in connect-src is dropped ('self' covers it).
 */
import { cp, mkdir, readFile, rm, writeFile, access } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const sfDist = join(repo, "apps/storefront/dist");
const adDist = join(repo, "apps/admin/dist");
const out = join(repo, "dist-site");

const exists = (p) => access(p).then(() => true, () => false);
for (const [label, p] of [["storefront", sfDist], ["admin", adDist]]) {
  if (!(await exists(join(p, "index.html")))) {
    console.error(`[assemble-site] ${label} build output missing (${p}/index.html). Run the app builds first (turbo run build).`);
    process.exit(1);
  }
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });
await cp(sfDist, out, { recursive: true });
await cp(adDist, join(out, "admin"), { recursive: true });
await rm(join(out, "admin", "_headers"), { force: true }); // only the root _headers is honoured; merged below

/** Parse a Pages-style `_headers` file: { "/path": Map(headerName -> value) } (comments ignored). */
function parse(text) {
  const rules = new Map();
  let cur = null;
  for (const raw of text.split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith("#")) continue;
    if (!/^\s/.test(raw)) { cur = new Map(); rules.set(raw.trim(), cur); continue; }
    const m = raw.trim().match(/^([^:]+):\s*(.*)$/);
    if (m && cur) cur.set(m[1].trim(), m[2].trim());
  }
  return rules;
}
const clean = (v) => v.replace(/\s+https:\/\/api\.example\.com/g, "").replace(/https:\/\/api\.example\.com\s*/g, "");
const read = async (p) => ((await exists(p)) ? readFile(p, "utf8") : "");

const sf = parse(await read(join(sfDist, "_headers"))).get("/*") ?? new Map();
const ad = parse(await read(join(adDist, "_headers"))).get("/*") ?? new Map();

const lines = [
  "# Generated by tooling/deploy/assemble-site.mjs. Edit apps/*/public/_headers instead.",
  "# Storefront headers apply to every path; the /admin/* block detaches (!) and overrides only what differs.",
  "/*",
  ...[...sf].map(([k, v]) => `  ${k}: ${clean(v)}`),
  "",
  "/admin/*",
];
for (const [k, v] of ad) {
  const val = clean(v);
  if (sf.has(k)) {
    if (clean(sf.get(k)) === val) continue; // identical: already applied by /*, avoid duplicate values
    lines.push(`  ! ${k}`);
  }
  lines.push(`  ${k}: ${val}`);
}
lines.push("");
await writeFile(join(out, "_headers"), lines.join("\n"));
console.log(`[assemble-site] wrote ${out} (storefront at /, admin at /admin/, merged _headers)`);
