#!/usr/bin/env node
// Regenerates packages/shared/src/trGeo.ts: Turkey's provinces and districts, spelled exactly as the shipping provider
// (Geliver) expects them. Source: Geliver's public geo endpoints (docs.geliver.io: list_cities, list_districts).
//   node tooling/geo/gen-tr-geo.mjs
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const BASE = "https://api.geliver.io/api/v1";
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), "../../packages/shared/src/trGeo.ts");
const get = async (path) => {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(BASE + path, { headers: { accept: "application/json" } });
      const j = await r.json();
      if (r.ok && j.result && Array.isArray(j.data)) return j.data;
    } catch { /* retry */ }
    await new Promise((r) => setTimeout(r, 800 * (i + 1)));
  }
  throw new Error(`failed: ${path}`);
};
const tr = new Intl.Collator("tr");
const cities = (await get("/cities?countryCode=TR")).filter((c) => /^\d{2}$/.test(c.cityCode)).sort((a, b) => tr.compare(a.name, b.name));
if (cities.length !== 81) throw new Error(`expected 81 provinces, got ${cities.length}`);
const rows = [];
let total = 0;
for (const c of cities) {
  const ds = [...new Set((await get(`/districts?countryCode=TR&cityCode=${c.cityCode}`)).map((d) => String(d.name).trim()).filter(Boolean))].sort(tr.compare);
  if (!ds.length) throw new Error(`no districts for ${c.name}`);
  total += ds.length;
  rows.push(`  [${JSON.stringify(c.cityCode)}, ${JSON.stringify(c.name)}, ${JSON.stringify(ds)}],`);
}
writeFileSync(OUT, `// GENERATED by tooling/geo/gen-tr-geo.mjs from Geliver's public geo endpoints. Do not edit by hand.
// ${cities.length} provinces, ${total} districts; names are spelled the way the shipping provider expects them.
/** [plate code, province, districts], provinces and districts sorted alphabetically (Turkish collation). */
export const TR_GEO: readonly (readonly [code: string, name: string, districts: readonly string[]])[] = [
${rows.join("\n")}
];
`);
console.log(`wrote ${OUT}: ${cities.length} provinces, ${total} districts`);
